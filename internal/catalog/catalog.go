package catalog

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"sync"
	"time"

	"opencode-proxy/internal/picker"
)

// catalogTTL is how long a fetched model catalog is served before it is
// fetched again. The picker is read when the app starts and when a model menu
// opens, so a few minutes of staleness costs nothing and keeps the gateway
// out of the hot path.
const catalogTTL = 10 * time.Minute

// Entry is one model of the gateway catalog as the picker sees it.
type Entry struct {
	ID     string // id the gateway knows
	Picker string // id the desktop app shows and sends back
	Name   string
}

// Catalog caches the gateway's own model list so the picker reflects the
// subscription rather than a snapshot file that has to be regenerated by hand.
type Catalog struct {
	mu       sync.Mutex
	ttl      time.Duration
	url      string
	fetched  time.Time
	entries  []Entry
	byPicker map[string]string
}

func New() *Catalog {
	return &Catalog{ttl: catalogTTL, byPicker: map[string]string{}}
}

// Get returns the catalog, fetching it when the cache is cold or stale. The
// caller's credentials are forwarded, because the gateway answers with the
// models of the subscription that token belongs to.
func (c *Catalog) Get(ctx context.Context, url string, hc *http.Client, authorization string) ([]Entry, error) {
	if c == nil || hc == nil {
		return nil, fmt.Errorf("catalog: unavailable")
	}
	c.mu.Lock()
	if c.url == url && len(c.entries) > 0 && time.Since(c.fetched) < c.ttl {
		out := append([]Entry(nil), c.entries...)
		c.mu.Unlock()
		return out, nil
	}
	c.mu.Unlock()

	entries, err := fetchCatalog(ctx, url, hc, authorization)
	if err != nil {
		return nil, err
	}

	byPicker := make(map[string]string, len(entries))
	for _, e := range entries {
		byPicker[strings.ToLower(e.Picker)] = e.ID
	}
	c.mu.Lock()
	c.url, c.entries, c.byPicker, c.fetched = url, entries, byPicker, time.Now()
	c.mu.Unlock()
	return entries, nil
}

// Lookup resolves a picker name from the cached catalog without touching the
// network, so it is safe on the request path.
func (c *Catalog) Lookup(name string) (string, bool) {
	if c == nil {
		return "", false
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if len(c.byPicker) == 0 {
		return "", false
	}
	id, ok := c.byPicker[strings.ToLower(strings.TrimSpace(name))]
	return id, ok
}

// URLFor is the gateway's model list endpoint: the configured catalog URL
// when set, otherwise derived from the inference endpoint the proxy knows.
func URLFor(catalogURL, upstream string) string {
	if catalogURL != "" {
		return catalogURL
	}
	base := strings.TrimSuffix(upstream, "/")
	base = strings.TrimSuffix(base, "/anthropic")
	return base + "/v1/models"
}

// fetchCatalog reads the gateway catalog and names every model the way the
// desktop app expects.
func fetchCatalog(ctx context.Context, url string, hc *http.Client, authorization string) ([]Entry, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("accept", "application/json")
	if authorization != "" {
		req.Header.Set("authorization", authorization)
	}
	req.Header.Set("x-opencode-session", "opencode-proxy-catalog")

	resp, err := hc.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("catalog: HTTP %d", resp.StatusCode)
	}

	var doc struct {
		Data []struct {
			ID   string `json:"id"`
			Name string `json:"name"`
		} `json:"data"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&doc); err != nil {
		return nil, fmt.Errorf("catalog: decode: %w", err)
	}

	entries := make([]Entry, 0, len(doc.Data))
	seen := make(map[string]bool, len(doc.Data))
	for _, m := range doc.Data {
		if m.ID == "" {
			continue
		}
		p := picker.Name(m.ID, m.Name)
		key := strings.ToLower(p)
		if seen[key] {
			continue
		}
		seen[key] = true
		name := m.Name
		if name == "" {
			name = m.ID
		}
		entries = append(entries, Entry{ID: m.ID, Picker: p, Name: name})
	}
	return entries, nil
}
